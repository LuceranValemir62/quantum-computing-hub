## 🧠 Key Concepts You Must Master

1. A **qubit** is a vector in a 2-dimensional complex Hilbert space: |ψ⟩ = α|0⟩ + β|1⟩
2. **Superposition** means the qubit exists in a linear combination until measured.
3. **Entanglement** is a non-classical correlation with no local hidden variable explanation.
4. **Quantum gates** are unitary matrices (U†U = I) acting on qubit states.
5. **Measurement** collapses the state probabilistically per the Born rule.

